#!/usr/bin/env node
/**
 * R6 §12 · renders the pallet, the carton, the full wrapped pallet and a single carton (scene.html) into
 * public/assets/pallet/<layer>-<w>.webp, and the 18 carton cells into src/content/palletCells.ts.
 *   cd site && node scripts/palletfilm/render.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const require = createRequire(import.meta.url);
let pw; try { pw = require('playwright'); } catch { pw = require('/opt/node22/lib/node_modules/playwright'); }
const OUT = path.join(ROOT, 'public/assets/pallet'), PNG = path.join(OUT, '.png'); fs.mkdirSync(PNG, { recursive: true });
const b = await pw.chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const p = await b.newPage({ viewport: { width: 1600, height: 1400 } });
await p.route('http://shot.local/**', (r) => {
  const u = new URL(r.request().url()).pathname;
  const file = u.startsWith('/three/') ? path.join(ROOT, 'node_modules', u) : path.join(ROOT, 'scripts/palletfilm', u);
  if (!fs.existsSync(file)) return r.fulfill({ status: 404, body: '' });
  r.fulfill({ status: 200, body: fs.readFileSync(file), headers: { 'content-type': file.endsWith('.js') ? 'application/javascript' : 'text/html' } });
});
p.on('pageerror', (e) => console.error('page error', e.message));
let cells = null;
for (const layer of ['pallet', 'carton', 'full', 'single']) {
  await p.goto('http://shot.local/scene.html?' + new URLSearchParams({ layer, w: '1200' }));
  await p.waitForFunction(() => window.__done, null, { timeout: 300000 });
  if (layer === 'carton') cells = await p.evaluate(() => window.__cells);
  const png = path.join(PNG, layer + '.png');
  await p.locator('canvas').screenshot({ path: png, omitBackground: true });
  // full-canvas layers keep their frame (they register); the single carton is cropped to its outline
  execFileSync('python3', ['-I', '-c', `
import sys
from PIL import Image
im=Image.open(sys.argv[1]).convert('RGBA')
if sys.argv[3]=='single':
    bb=im.split()[3].point(lambda v:255 if v>30 else 0).getbbox(); im=im.crop((max(0,bb[0]-10),max(0,bb[1]-10),min(im.width,bb[2]+10),min(im.height,bb[3]+10)))
for w in (600,1200):
    r=im.resize((w,round(im.height*w/im.width)),Image.LANCZOS) if w<im.width else im
    r.save(sys.argv[2]+'-%d.webp'%w,quality=86,method=6)
`, png, path.join(OUT, layer), layer]);
  console.log('rendered', layer);
}
// cells in units of the 1200px frame; the page scales them with the stage
const order = cells.map((c, i) => ({ ...c, i })).sort((a, b) => b.d - a.d).map((c, k) => ({ c: c.c, r: c.r, l: c.l, dx: c.dx, dy: c.dy, z: k }));
const byIndex = cells.map((c) => order.find((o) => o.c === c.c && o.r === c.r && o.l === c.l));
fs.writeFileSync(path.join(ROOT, 'src/content/palletCells.ts'), `// Generated by scripts/palletfilm/render.mjs: where carton n lands (px in the 1200 × 1008 frame, relative to cell 0) and its draw order.\n// n runs layer by layer, back row first, left to right, so a growing order fills the pallet like a real one.\nexport const PALLET_FRAME = { w: 1200, h: 1008 };\nexport const PALLET_CELLS: { c: number; r: number; l: number; dx: number; dy: number; z: number }[] = ${JSON.stringify(byIndex)};\n`);
await b.close();
